// The medicines on the Essential Medicines and Health Supplies List for Uganda
// (EMHSLU) 2023, Section A - published by the Ministry of Health, and the list
// National Medical Stores procures and supplies against. Each formulation is
// written here as the list gives it (strength and dosage form), under the name
// the prescribing list already uses where the two differ (Lidocaine for
// "Lignocaine", Adrenaline for "Epinephrine"), so a medicine is listed once.
// Merged into the prescribing list in medicines-catalog.ts.
//
// Left out on purpose: health supplies that are not prescribed (disinfectants,
// condoms, beads and devices), diagnostic agents and contrast media, dialysis
// concentrates, blood components, and the routine immunisation vaccines (given
// and recorded through immunisation, not prescribed). Where the printed list
// has an obvious misprint (a lost "micro" sign: "Misoprostol 200 g"), the
// strength is written as the medicine is actually made (200 mcg).

